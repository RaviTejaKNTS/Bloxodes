export function getFieldLabel(key: string, fieldLabels?: Record<string, string> | null): string {
  return fieldLabels?.[key] ?? FIELD_LABELS[key] ?? humanizeKey(key);
}

export function getCollectionFieldLabels(display: unknown, itemFields: string[] = []): Record<string, string> {
  if (!display || typeof display !== "object" || Array.isArray(display)) return {};
  const { fieldLabels, fieldPresentation } = display as Record<string, unknown>;
  const presentationLabels = fieldPresentation && typeof fieldPresentation === "object" && !Array.isArray(fieldPresentation)
    ? Object.entries(fieldPresentation).flatMap(([key, value]) =>
      value && typeof value === "object" && "label" in value && typeof value.label === "string" && value.label.trim() ? [[key, value.label]] : []
    ) : [];
  const hasFieldLabels = typeof fieldLabels === "object" && fieldLabels !== null && !Array.isArray(fieldLabels);
  const labels = hasFieldLabels
    ? Object.entries(fieldLabels).filter(([, value]) => typeof value === "string" && value.trim()) : [];
  const fallbacks = hasFieldLabels ? Object.fromEntries(itemFields.map(key => [key, getFieldLabel(key)])) : {};
  return { ...fallbacks, ...Object.fromEntries(presentationLabels), ...Object.fromEntries(labels) };
}

export function getUsefulColumnLabels(columns: string[], limit = 6): string[] {
  const labels = columns
    .filter((key) => !OMITTED_FIELD_KEYS.has(key))
    .map(key => getFieldLabel(key))
    .filter(Boolean);
  return Array.from(new Set(labels)).slice(0, limit);
}

function humanizeKey(value: string): string {
  return value
    .replace(/[_-]/g, " ")
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(" ")
    .filter(Boolean)
    .map((word) => {
      const upper = word.toUpperCase();
      if (["npc", "npcs", "xp", "ugc"].includes(word.toLowerCase())) return upper;
      return word.charAt(0).toUpperCase() + word.slice(1).toLowerCase();
    })
    .join(" ");
}

